// Copies the customer review page from apps/review-web into the website, so
// https://revyneai.com/r/<code> serves it.
//   node apps/website/tools/sync-review-web.mjs
//
// apps/review-web stays the source of truth and keeps working on its own (it
// expects to be served from a site root). Here its assets live under /review/
// and the page under /r/, so the absolute asset paths are rewritten. Assets are
// kept out of /r/ on purpose: the `/r/*` rewrite must never swallow a JS/CSS
// request. Re-run this after changing anything in apps/review-web.
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const site = fileURLToPath(new URL("..", import.meta.url));
const src = fileURLToPath(new URL("../../review-web/", import.meta.url));
const stamp = "Generated by apps/website/tools/sync-review-web.mjs from apps/review-web — edit the source, not this copy.";

const assets = ["app.js", "styles.css", "config.js", "logo.png"];
const rewrite = (s) => s.replace(/(["'(`])\/(app\.js|styles\.css|config\.js|logo\.png)\b/g, "$1/review/$2");

await mkdir(site + "review", { recursive: true });
await mkdir(site + "r", { recursive: true });

for (const name of assets) {
  if (name.endsWith(".js") || name.endsWith(".css")) {
    const text = await readFile(src + name, "utf8");
    await writeFile(site + "review/" + name, `/* ${stamp} */\n` + rewrite(text));
  } else {
    await copyFile(src + name, site + "review/" + name);
  }
}

const html = await readFile(src + "index.html", "utf8");
await writeFile(site + "r/index.html", rewrite(html).replace("<!doctype html>", `<!doctype html>\n<!-- ${stamp} -->`));

console.log("Synced apps/review-web -> apps/website/r/ and apps/website/review/");
